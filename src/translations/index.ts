export const getTranslation = (
  lang: LanguageCode,
  key: keyof Translations,
  defaultText?: string
): string => {
  const dict = TRANSLATIONS[lang];
  if (dict && dict[key]) {
    return dict[key];
  }
  const enDict = TRANSLATIONS.en;
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return defaultText || (key as string);
};
